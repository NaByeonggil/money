const warn = (text: string): Entry => ({ id: newId(), type: "warn", text });
const list = (...texts: string[]): Entry => ({
  id: newId(),
  type: "list",
  items: texts.map((t) => ({ id: newId(), text: t })),
});
const check = (...texts: string[]): Entry => ({
  id: newId(),
  type: "checklist",
  items: texts.map((t) => ({ id: newId(), text: t, done: false })),
});
const table = (columns: string[], rows: string[][], headerColumn = false): Entry => ({
  id: newId(),
  type: "table",
  columns,
  rows: rows.map((cells) => ({ id: newId(), cells })),
  headerColumn,
});

